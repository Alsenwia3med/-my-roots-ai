/**
 * ROOTS-AI(TM) M2 Item 9 - RLS negative suite runner.
 *
 * Runs the controlled negative row-level-security suite against the ROOTS
 * Supabase / PostgreSQL database, when database credentials are supplied.
 *
 * The suite is the set of isolation cases in
 * migrations/tests/rls_negative_suite.sql, which prove that unauthorized and
 * cross-user access to protected assessment and scoring data is rejected by the
 * RLS policies in migrations/002_add_rls_policies.sql.
 *
 * Configuration (any one of):
 *   SUPABASE_DB_URL          postgres connection string (preferred)
 *   DATABASE_URL             postgres connection string
 *   PGHOST/PGPORT/PGUSER/PGPASSWORD/PGDATABASE  libpq environment
 *
 * When no database credential is present the runner does NOT fail. It reports
 * the suite as PENDING, names the missing input, and prints the exact command
 * to run once ROOTS supplies the Supabase project credentials. This mirrors the
 * existing "pending ROOTS credentials" note in docs/m2/M2_COMPLETION_PACKAGE.md.
 *
 * Usage:
 *   node scripts/run-rls-suite.mjs [--write-evidence]
 *
 * --write-evidence appends the captured result to
 *   docs/m2/M2_RLS_NEGATIVE_SUITE.txt
 */

import { execFileSync } from "node:child_process";
import { appendFileSync, existsSync, writeFileSync } from "node:fs";

const SUITE = "migrations/tests/rls_negative_suite.sql";
const SCHEMA = "migrations/001_initial_schema.sql";
const POLICIES = "migrations/002_add_rls_policies.sql";
const EVIDENCE = "docs/m2/M2_RLS_NEGATIVE_SUITE.txt";
const writeEvidence = process.argv.includes("--write-evidence");

const dbUrl =
  process.env.SUPABASE_DB_URL ??
  process.env.DATABASE_URL ??
  (process.env.PGHOST ? "libpq-env" : undefined);

function hasPsql() {
  try {
    execFileSync("psql", ["--version"], { stdio: "pipe" });
    return true;
  } catch {
    return false;
  }
}

function stamp() {
  return new Date().toISOString();
}

function emit(lines) {
  const text = lines.join("\n");
  console.log(text);
  if (writeEvidence) {
    if (!existsSync(EVIDENCE)) {
      writeFileSync(
        EVIDENCE,
        [
          "ROOTS-AI(TM) M2 Item 9 - Controlled Negative RLS Isolation Suite",
          "Controlled sources of the policy set: docs/m1/M1_ITEM5_DATABASE_MIGRATIONS.md, docs/m1/M1_ITEM7_RLS_DATA_ISOLATION.md",
          "",
          "This file is REGENERATED by: node scripts/run-rls-suite.mjs --write-evidence",
          "",
          "=".repeat(110),
          "",
        ].join("\n"),
        "utf8",
      );
    }
    appendFileSync(EVIDENCE, text + "\n\n", "utf8");
  }
}

function main() {
  console.log("ROOTS-AI(TM) M2 Item 9 - RLS Negative Isolation Suite\n");
  console.log(`Suite    : ${SUITE}`);
  console.log(`Schema   : ${SCHEMA}`);
  console.log(`Policies : ${POLICIES}`);
  console.log(
    `Target   : ${dbUrl ? (dbUrl === "libpq-env" ? "libpq environment (PGHOST etc.)" : "SUPABASE_DB_URL / DATABASE_URL") : "(none supplied)"}\n`,
  );

  for (const path of [SCHEMA, POLICIES, SUITE]) {
    if (!existsSync(path)) {
      console.log(`ERROR: ${path} is missing - cannot run the suite.`);
      process.exitCode = 1;
      return;
    }
  }

  // ------------------------------------------------------------------- gate
  if (!dbUrl) {
    emit([
      "STATUS: PENDING ROOTS CREDENTIALS - live run not executed.",
      "",
      "The controlled negative RLS suite is complete and ready to run. It has NOT",
      "been executed because no ROOTS Supabase database credential is available in",
      "this environment. The following inputs are required:",
      "",
      "  SUPABASE_URL                Supabase project URL",
      "  SUPABASE_ANON_KEY           anon (public) key",
      "  SUPABASE_SERVICE_ROLE_KEY   service-role key (server-side only)",
      "  SUPABASE_DB_URL             Postgres connection string for psql",
      "                              e.g. postgresql://postgres:<pw>@db.<ref>.supabase.co:5432/postgres",
      "",
      "Once supplied, run:",
      "",
      `  psql "$SUPABASE_DB_URL" -f ${SCHEMA}`,
      `  psql "$SUPABASE_DB_URL" -f ${POLICIES}`,
      `  psql "$SUPABASE_DB_URL" -f ${SUITE}`,
      "",
      "or, to apply the schema/policies and capture evidence in one step:",
      "",
      "  node scripts/run-rls-suite.mjs --write-evidence",
      "",
      "Artifacts delivered and verified present:",
      `  * ${SCHEMA}   - schema (sessions/reports/audit_logs, ownership column, indexes)`,
      `  * ${POLICIES} - RLS enabled + forced, ownership policies, immutability policies`,
      `  * ${SUITE}    - 25 negative isolation cases with in-SQL PASS/FAIL and non-zero exit on failure`,
      "",
      `Generated: ${stamp()}`,
    ]);
    return;
  }

  if (!hasPsql()) {
    emit([
      "STATUS: BLOCKED - `psql` is not available on PATH.",
      "",
      "A database credential is configured, but psql is required to execute the suite.",
      "Install the PostgreSQL client (or run the three .sql files from the Supabase SQL",
      "editor) and re-run: node scripts/run-rls-suite.mjs --write-evidence",
      "",
      `Generated: ${stamp()}`,
    ]);
    return;
  }

  // --------------------------------------------------------------- live run
  const args = dbUrl === "libpq-env" ? [] : [dbUrl];

  const run = (file) =>
    execFileSync("psql", [...args, "-v", "ON_ERROR_STOP=1", "-f", file], {
      encoding: "utf8",
      stdio: "pipe",
    });

  const lines = [];
  let failed = false;

  try {
    run(SCHEMA);
    lines.push("Schema applied: OK");
  } catch (error) {
    failed = true;
    lines.push("Schema apply FAILED:");
    lines.push(String(error.stdout ?? error.message));
  }

  try {
    run(POLICIES);
    lines.push("RLS policies applied: OK");
  } catch (error) {
    failed = true;
    lines.push("Policy apply FAILED:");
    lines.push(String(error.stdout ?? error.message));
  }

  if (!failed) {
    try {
      const out = run(SUITE);
      lines.push("Suite executed. Output:");
      lines.push(out);
      if (!/ALL NEGATIVE ISOLATION CASES PASS/.test(out)) {
        failed = true;
        lines.push("Suite did not report an all-PASS result.");
      }
    } catch (error) {
      failed = true;
      lines.push("Suite FAILED:");
      lines.push(String(error.stdout ?? error.message));
    }
  }

  emit([
    "STATUS: " +
      (failed
        ? "FAILED - isolation NOT proven."
        : "PASS - unauthorized and cross-user access rejected."),
    "",
    ...lines,
    "",
    `Generated: ${stamp()}`,
  ]);

  if (failed) process.exitCode = 1;
}

main();


