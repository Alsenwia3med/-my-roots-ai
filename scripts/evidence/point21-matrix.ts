/**
 * The rendered text for a domain at a classification, taken from the real builder rather than
 * assembled here, so the matrix cannot show wording the report does not actually produce.
 */
function renderedSamples(): Map<string, string> {
  const out = new Map<string, string>();
  for (const c of golden.cases) {
    const scoring = computeScores(c.input as unknown as NormalizedInput);
    const report = buildReport({
      reportId: `RPT-P21-${c.test_id}`,
      generatedAt: '2026-09-29T12:00:00.000Z',
      participantDisplay: null,
      questionnaireVersion: '1.0.1',
      auditTraceReference: `scores/${c.test_id}`,
      scoring,
      protective: { P1: true, P2: true, P3: false, P4: false, P5: true },
      answers: {},
    });
    for (const item of report.sections[6].items ?? []) {
      const domain = DOMAIN_DISPLAY_ORDER.find((d) => DOMAIN_LABELS[d] === item.label);
      if (!domain) continue;
      const band = BANDS.find((b) => item.note?.includes(CLASSIFICATION_EXPLANATIONS[b.label]));
      if (!band) continue;
      const key = `${domain}|${band.label}`;
      if (!out.has(key)) out.set(key, item.note ?? '');
    }
  }
  return out;
}

