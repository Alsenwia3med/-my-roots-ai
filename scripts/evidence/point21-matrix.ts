/**
 * Report-review point 21 — seven-domain x four-classification content matrix.
 *
 *     npm run evidence:point21
 *
 * ROOTS decision of 29 September 2026, item 6: "Keep point 21 open... Please prepare the
 * proposed seven-domain x four-classification matrix using the existing approved content only.
 * For each combination, include the domain, classification, approved domain meaning, approved
 * classification explanation, exact current rendered text, source references, content
 * identifiers, and any relevant approved material that could support additional interpretation.
 * Mark any missing domain-specific interpretation as requiring ROOTS content approval."
 *
 * And, emphatically: "Do not fill those cells with newly authored physiological or medical
 * claims, and do not generate variations merely to make all 28 cells sound different. The matrix
 * is a review instrument, not an instruction to create 28 new interpretations."
 *
 * This script therefore authors nothing. Every string it prints is read from the controlled
 * content module, and the "current rendered text" column is produced by the real report builder,
 * so what ROOTS reviews is exactly what a participant sees. The interpretation column is left
 * empty and marked as requiring ROOTS approval.
 */

